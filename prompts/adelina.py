def build_user_state_block(state: dict) -> str:
    """Compact runtime context injected each turn."""
    import json

    return (
        "USER_STATE (внутренняя память; не цитируй JSON пользователю):\n"
        + json.dumps(state, ensure_ascii=False, indent=2)
    )
